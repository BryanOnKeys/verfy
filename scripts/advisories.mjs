// Validate advisories/**/*.json (OSV format with an Atls severity label) and
// build the SQL migration that publishes them.
//
//   node scripts/advisories.mjs           validate + check the migration is up to date (CI)
//   node scripts/advisories.mjs --write   regenerate the migration after adding an advisory
//
// Advisories are added by pull request: each needs at least one public source
// in `references`. `database_specific.atls_review` stays "unreviewed" until a
// maintainer has reproduced the issue; the UI never shows unreviewed entries as verified.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "advisories");
const MIGRATION = path.join(ROOT, "supabase", "migrations", "20261011000300_advisories_initial.sql");
const ID = /^ATLS-\d{4}-\d{4,}$/;
const SEVERITIES = new Set(["critical", "high", "medium", "low"]);

function files() {
  return readdirSync(DIR, { recursive: true })
    .map(String)
    .filter((f) => f.endsWith(".json"))
    .sort();
}

export function load() {
  const out = [];
  const problems = [];
  for (const rel of files()) {
    const file = path.join(DIR, rel);
    let a;
    try {
      a = JSON.parse(readFileSync(file, "utf8"));
    } catch (e) {
      problems.push(`${rel}: not valid JSON (${e.message})`);
      continue;
    }
    const where = `${rel}`;
    if (!ID.test(a.id ?? "")) problems.push(`${where}: id must look like ATLS-2025-0001`);
    if (path.basename(rel, ".json") !== a.id) problems.push(`${where}: file name must equal the id`);
    if (typeof a.summary !== "string" || a.summary.length < 5 || a.summary.length > 300) problems.push(`${where}: summary must be 5-300 characters`);
    if (typeof a.details !== "string" || !a.details.trim()) problems.push(`${where}: details are required`);
    if (!SEVERITIES.has(a.severity_label)) problems.push(`${where}: severity_label must be critical, high, medium or low`);
    if (!Array.isArray(a.affected) || !a.affected.length || !a.affected.every((x) => x?.package?.ecosystem && x?.package?.name)) problems.push(`${where}: affected[].package {ecosystem, name} is required`);
    if (!Array.isArray(a.references) || !a.references.length || !a.references.every((r) => typeof r.url === "string" && r.url.startsWith("https://"))) problems.push(`${where}: at least one https reference is required`);
    for (const k of ["published", "modified"]) if (Number.isNaN(Date.parse(a[k]))) problems.push(`${where}: ${k} must be an RFC 3339 timestamp`);
    if (!["unreviewed", "reviewed"].includes(a.database_specific?.atls_review)) problems.push(`${where}: database_specific.atls_review must be unreviewed or reviewed`);
    out.push(a);
  }
  const ids = out.map((a) => a.id);
  if (new Set(ids).size !== ids.length) problems.push("duplicate advisory ids");
  return { advisories: out, problems };
}

const lit = (v) => (v === null || v === undefined ? "null" : "'" + String(v).replace(/'/g, "''") + "'");

export function sql(advisories) {
  const lines = [
    "-- Generated by scripts/advisories.mjs from advisories/**/*.json. Do not edit by hand.",
    "-- Public, sourced advisories. review_status stays 'unreviewed' until a maintainer reproduces the issue.",
  ];
  for (const a of advisories) {
    const pkg = a.affected[0].package;
    lines.push(
      `insert into public.advisories (id, summary, details, severity, ecosystem, package, affected, aliases, "references", published, modified, status, review_status, body)
values (${lit(a.id)}, ${lit(a.summary)}, ${lit(a.details)}, ${lit(a.severity_label)}, ${lit(pkg.ecosystem)}, ${lit(pkg.name)},
  ${lit(JSON.stringify(a.affected))}::jsonb, array[${(a.aliases ?? []).map(lit).join(", ")}]::text[], ${lit(JSON.stringify(a.references))}::jsonb,
  ${lit(a.published)}, ${lit(a.modified)}, 'published', ${lit(a.database_specific.atls_review)}, ${lit(JSON.stringify(a))}::jsonb)
on conflict (id) do update set summary = excluded.summary, details = excluded.details, severity = excluded.severity,
  ecosystem = excluded.ecosystem, package = excluded.package, affected = excluded.affected, aliases = excluded.aliases,
  "references" = excluded."references", modified = excluded.modified, review_status = excluded.review_status, body = excluded.body;`,
    );
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { advisories, problems } = load();
  if (problems.length) {
    console.error("Advisory problems:\n  " + problems.join("\n  "));
    process.exit(1);
  }
  const text = sql(advisories);
  if (process.argv.includes("--write")) {
    writeFileSync(MIGRATION, text);
    console.log(`wrote ${path.relative(ROOT, MIGRATION)} (${advisories.length} advisories)`);
  } else if (!existsSync(MIGRATION) || readFileSync(MIGRATION, "utf8").replace(/\r\n/g, "\n") !== text) {
    console.error("The advisories migration is out of date. Run: node scripts/advisories.mjs --write");
    process.exit(1);
  } else {
    console.log(`OK  ${advisories.length} advisories valid, migration up to date`);
  }
}
