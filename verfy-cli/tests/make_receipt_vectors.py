"""Write tests/fixtures/receipts.json: signed `verfy.receipt/1` vectors from the
Python implementation, with a fixed test key, for the TypeScript server
verifier (src/core/receipts.test.ts) and the ingest tests.

The key is a TEST key (secret bytes 1..32). Never use it for anything else.
Ed25519 is deterministic, so running this twice gives identical bytes.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from verfy import check, load_policy  # noqa: E402
from verfy.canonical import digest  # noqa: E402
from verfy.receipts import Key, b64u, build_receipt, receipt_hash, sign_receipt  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "receipts.json"


def make() -> dict:
    key = Key(bytes(range(1, 33)))
    pol = load_policy({"home": "/home/you", "workspace": "/home/you/project"})
    pol_sha = digest(pol)
    actions = [
        ({"server": "claude-code", "tool": "Bash", "arguments": {"command": "npm test"}}, {"status": "ok", "result_sha256": digest({"exit": 0})}),
        ({"server": "claude-code", "tool": "Bash", "arguments": {"command": "rm -rf ~"}}, {"status": "blocked", "result_sha256": None}),
        ({"server": "github", "tool": "merge_pull_request", "arguments": {"pr": 42, "note": "ünïcode ✓ 😀"}}, {"status": "asked", "result_sha256": None}),
        ({"server": "filesystem", "tool": "read_file", "arguments": {"path": "/home/you/.ssh/id_rsa"}}, {"status": "asked", "result_sha256": None}),
    ]
    receipts, prev = [], None
    for i, (act, outcome) in enumerate(actions):
        body = build_receipt(seq=i, prev=prev, agent="vector-agent", session="ses_vectors", action=act, decision=check(act, pol),
                             outcome=outcome, policy_sha256=pol_sha, tool_sha256=None,
                             issued_at=f"2026-10-11T09:00:0{i}.000Z", rid=f"rcpt_vector{i:04d}")
        r = sign_receipt(body, key)
        receipts.append(r)
        prev = receipt_hash(r)
    return {
        "note": "Generated by verfy-cli/tests/make_receipt_vectors.py with a TEST key. Do not edit by hand.",
        "public_key": b64u(key.public),
        "kid": key.kid,
        "receipts": receipts,
        "hashes": [receipt_hash(r) for r in receipts],
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(make(), indent=1, ensure_ascii=False) + "\n", "utf-8")
    print(f"wrote {OUT}")
